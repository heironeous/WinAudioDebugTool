// Generates src/AudioDeviceDebugger/Interop/PropertyKeyNames.g.cs from Microsoft.Windows.SDK.Win32Metadata.
//
// In Windows.Win32.winmd every PKEY_* / DEVPKEY_* is a field carrying a ConstantAttribute whose string value is
//   "{Data1, Data2, Data3, b0, b1, b2, b3, b4, b5, b6, b7}, pid"   (all decimal)
// This tool reads those, de-duplicates keys that are declared under several names, and writes a C# table.

using System.Globalization;
using System.Reflection;
using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Text;
using System.Text.RegularExpressions;

string packageDir = typeof(Program).Assembly.GetCustomAttributes<AssemblyMetadataAttribute>()
    .Single(a => a.Key == "Win32MetadataPackageDir").Value!;
string winmdPath = Path.Combine(packageDir, "Windows.Win32.winmd");
string packageVersion = new DirectoryInfo(packageDir).Name;

string outputPath = args.Length > 0
    ? Path.GetFullPath(args[0])
    : Path.Combine(FindRepoRoot(), "src", "AudioDeviceDebugger", "Interop", "PropertyKeyNames.g.cs");

var constantPattern = new Regex(@"^\{(\d+), (\d+), (\d+), (\d+), (\d+), (\d+), (\d+), (\d+), (\d+), (\d+), (\d+)\}, (\d+)$");
var namesByKey = new Dictionary<(Guid FormatId, int PropertyId), SortedSet<string>>();

using (var stream = File.OpenRead(winmdPath))
using (var pe = new PEReader(stream))
{
    var md = pe.GetMetadataReader();
    foreach (var typeHandle in md.TypeDefinitions)
    {
        foreach (var fieldHandle in md.GetTypeDefinition(typeHandle).GetFields())
        {
            var field = md.GetFieldDefinition(fieldHandle);
            string name = md.GetString(field.Name);
            if (!name.StartsWith("PKEY_", StringComparison.Ordinal) && !name.StartsWith("DEVPKEY_", StringComparison.Ordinal))
            {
                continue;
            }

            string? constant = ReadConstantAttribute(md, field);
            var match = constant is null ? null : constantPattern.Match(constant);
            if (match is null || !match.Success)
            {
                Console.Error.WriteLine($"warning: skipping {name}: unrecognised constant '{constant}'");
                continue;
            }

            uint U(int g) => uint.Parse(match.Groups[g].Value, CultureInfo.InvariantCulture);
            var formatId = new Guid(U(1), (ushort)U(2), (ushort)U(3),
                (byte)U(4), (byte)U(5), (byte)U(6), (byte)U(7), (byte)U(8), (byte)U(9), (byte)U(10), (byte)U(11));
            var key = (formatId, (int)U(12));

            if (!namesByKey.TryGetValue(key, out var names))
            {
                namesByKey[key] = names = new SortedSet<string>(StringComparer.Ordinal);
            }
            names.Add(name);
        }
    }
}

var sb = new StringBuilder();
sb.AppendLine("// <auto-generated>");
sb.AppendLine($"//   Generated by tools/PropertyKeyNameGenerator from Microsoft.Windows.SDK.Win32Metadata {packageVersion}.");
sb.AppendLine("//   Do not edit by hand — re-run the generator. Add undocumented keys to PropertyKeyNames.cs instead.");
sb.AppendLine("// </auto-generated>");
sb.AppendLine();
sb.AppendLine("namespace AudioDeviceDebugger.Interop;");
sb.AppendLine();
sb.AppendLine("internal static partial class PropertyKeyNames");
sb.AppendLine("{");
sb.AppendLine($"    /// <summary>{namesByKey.Count} documented keys: (fmtid, pid) → SDK symbol name.</summary>");
sb.AppendLine("    private static readonly Dictionary<(Guid FormatId, int PropertyId), string> SdkNames = new()");
sb.AppendLine("    {");
foreach (var (key, names) in namesByKey.OrderBy(kv => kv.Key.FormatId.ToString()).ThenBy(kv => kv.Key.PropertyId))
{
    string preferred = PreferredName(names);
    string aliases = names.Count > 1 ? $" // also: {string.Join(", ", names.Where(n => n != preferred))}" : "";
    sb.AppendLine($"        [(new Guid(\"{key.FormatId}\"), {key.PropertyId})] = \"{preferred}\",{aliases}");
}
sb.AppendLine("    };");
sb.AppendLine("}");

File.WriteAllText(outputPath, sb.ToString(), new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
Console.WriteLine($"Wrote {namesByKey.Count} keys ({namesByKey.Sum(kv => kv.Value.Count)} names) to {outputPath}");
return;

// Several headers declare the same key (e.g. PKEY_Device_FriendlyName and DEVPKEY_Device_FriendlyName); prefer
// the PKEY_ spelling (what audio/property-store docs use), then the shortest, then ordinal order.
static string PreferredName(IEnumerable<string> names) => names
    .OrderBy(n => n.StartsWith("PKEY_", StringComparison.Ordinal) ? 0 : 1)
    .ThenBy(n => n.Length)
    .ThenBy(n => n, StringComparer.Ordinal)
    .First();

static string? ReadConstantAttribute(MetadataReader md, FieldDefinition field)
{
    foreach (var attributeHandle in field.GetCustomAttributes())
    {
        var attribute = md.GetCustomAttribute(attributeHandle);
        if (attribute.Constructor.Kind != HandleKind.MemberReference) continue;
        var parent = md.GetMemberReference((MemberReferenceHandle)attribute.Constructor).Parent;
        if (parent.Kind != HandleKind.TypeReference) continue;
        if (md.GetString(md.GetTypeReference((TypeReferenceHandle)parent).Name) != "ConstantAttribute") continue;

        var blob = md.GetBlobReader(attribute.Value);
        blob.ReadUInt16(); // prolog 0x0001
        return blob.ReadSerializedString();
    }
    return null;
}

static string FindRepoRoot()
{
    for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir is not null; dir = dir.Parent)
    {
        if (File.Exists(Path.Combine(dir.FullName, "AudioDeviceDebugger.sln"))) return dir.FullName;
    }
    throw new InvalidOperationException("Couldn't find AudioDeviceDebugger.sln above the tool's directory; pass the output path explicitly.");
}
